import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import type { Quadrant, ReleaseData, Ring, Technology } from "./types.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
// mcp/dist/data.js (or mcp/src/data.ts via tsx) -> repo root/radar/data.json
const DATA_PATH = path.join(__dirname, "..", "..", "radar", "data.json");

let cache: ReleaseData | undefined;

/**
 * Load radar/data.json, the enriched release data the root conversion
 * script (`npm run conv`) writes for the Vue front end. Cached after the
 * first read since the file is only regenerated by that script, never
 * at runtime.
 */
export function loadReleaseData(): ReleaseData {
  if (cache) {
    return cache;
  }

  let raw: unknown;
  try {
    raw = JSON.parse(fs.readFileSync(DATA_PATH, "utf8"));
  } catch (error) {
    throw new Error(
      `Could not read tech radar data at ${DATA_PATH}. ` +
        `Run "npm run conv" in the project root to generate it. ` +
        `Underlying error: ${error instanceof Error ? error.message : String(error)}`
    );
  }

  const data = raw as ReleaseData;
  if (!data || !Array.isArray(data.entries)) {
    throw new Error(`Expected ${DATA_PATH} to contain a "entries" array`);
  }

  cache = data;
  return cache;
}

function loadTechnologies(): Technology[] {
  return loadReleaseData().entries;
}

/**
 * Find technologies matching a name query against label, title or id.
 * Returns exact (case-insensitive) matches first; falls back to
 * substring matches when there is no exact match.
 */
export function findTechnologies(name: string): Technology[] {
  const technologies = loadTechnologies();
  const query = name.trim().toLowerCase();

  const exact = technologies.filter(
    (tech) =>
      tech.id.toLowerCase() === query ||
      tech.label.toLowerCase() === query ||
      tech.title.toLowerCase() === query
  );
  if (exact.length > 0) {
    return exact;
  }

  return technologies.filter(
    (tech) =>
      tech.label.toLowerCase().includes(query) || tech.title.toLowerCase().includes(query)
  );
}

export interface ListFilter {
  ring?: Ring;
  quadrant?: Quadrant;
}

export function listTechnologies(filter: ListFilter): Technology[] {
  return loadTechnologies().filter((tech) => {
    if (filter.ring && tech.ring !== filter.ring) {
      return false;
    }
    if (filter.quadrant && tech.quadrant !== filter.quadrant) {
      return false;
    }
    return true;
  });
}
